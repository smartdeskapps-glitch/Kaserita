ALTER TABLE public.clientes ADD COLUMN IF NOT EXISTS correo TEXT;
ALTER TABLE public.clientes ADD COLUMN IF NOT EXISTS limite_credito NUMERIC(10, 2) NOT NULL DEFAULT 200.00;

-- Ventas: anulación (soft-delete, conserva historial) y medio de pago mixto
ALTER TABLE public.ventas ADD COLUMN IF NOT EXISTS anulada BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE public.ventas ADD COLUMN IF NOT EXISTS motivo_anulacion TEXT;
ALTER TABLE public.ventas ADD COLUMN IF NOT EXISTS monto_efectivo NUMERIC(10, 2) DEFAULT 0.00;
ALTER TABLE public.ventas ADD COLUMN IF NOT EXISTS monto_otro NUMERIC(10, 2) DEFAULT 0.00;

-- Ventas Detalle: cantidad con decimales para productos a granel (ej. 0.350 KG)
ALTER TABLE public.ventas_detalle ALTER COLUMN cantidad TYPE NUMERIC(10, 3);

-- Turnos de Caja: arqueo ciego (esperado vs contado)
ALTER TABLE public.turnos_caja ADD COLUMN IF NOT EXISTS monto_final_real NUMERIC(10, 2);
ALTER TABLE public.turnos_caja ADD COLUMN IF NOT EXISTS ventas_sistema NUMERIC(10, 2) DEFAULT 0.00;
ALTER TABLE public.turnos_caja ADD COLUMN IF NOT EXISTS diferencia NUMERIC(10, 2);

-- TABLA: compras (cabecera de entrada de mercadería / abastecimiento)
CREATE TABLE IF NOT EXISTS public.compras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bodega_id TEXT NOT NULL,
    cajero_id TEXT,
    proveedor_nombre TEXT,
    proveedor_ruc TEXT,
    nro_comprobante TEXT,
    total_compra NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    fecha TIMESTAMPTZ DEFAULT NOW()
);

-- TABLA: compras_detalle
CREATE TABLE IF NOT EXISTS public.compras_detalle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compra_id BIGINT REFERENCES public.compras(id) ON DELETE CASCADE,
    producto_id BIGINT REFERENCES public.productos(id) ON DELETE SET NULL,
    cantidad NUMERIC(10, 3) NOT NULL DEFAULT 1,
    costo_unitario NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    subtotal NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- TABLA: pagos_credito (abonos / cancelaciones de deuda)
CREATE TABLE IF NOT EXISTS public.pagos_credito (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bodega_id TEXT NOT NULL,
    cliente_id BIGINT REFERENCES public.clientes(id) ON DELETE CASCADE,
    cajero_id TEXT,
    monto_pagado NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    saldo_anterior NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    saldo_restante NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    medio_pago TEXT NOT NULL DEFAULT 'EFECTIVO',
    fecha TIMESTAMPTZ DEFAULT NOW()
);

-- TABLA: ventas_espera (ventas "aparcadas" en espera de recuperación)
CREATE TABLE IF NOT EXISTS public.ventas_espera (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bodega_id TEXT NOT NULL,
    cajero_id TEXT NOT NULL,
    cliente_id BIGINT REFERENCES public.clientes(id) ON DELETE SET NULL,
    nombre_referencia TEXT,
    items JSONB NOT NULL,
    total NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- RLS para las tablas nuevas
ALTER TABLE public.compras ENABLE ROW LEVEL SECURITY;
