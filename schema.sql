-- 1. Habilitar extensión UUID si se requiere
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. TABLA: productos
CREATE TABLE IF NOT EXISTS public.productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bodega_id TEXT NOT NULL, -- o BIGINT si usas números
    cod_ean TEXT,
    descripcion TEXT NOT NULL,
    precio_costo NUMERIC(10, 2) DEFAULT 0.00,
    precio_venta NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    categoria TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TABLA: clientes
CREATE TABLE IF NOT EXISTS public.clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bodega_id TEXT NOT NULL,
    dni TEXT NOT NULL,
    nombre_completo TEXT NOT NULL,
    saldo_actual NUMERIC(10, 2) DEFAULT 0.00,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT clientes_bodega_dni_unique UNIQUE (bodega_id, dni)
);

-- 4. TABLA: turnos_caja
CREATE TABLE IF NOT EXISTS public.turnos_caja (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bodega_id TEXT NOT NULL,
    cajero_id TEXT NOT NULL,
    fecha_apertura TIMESTAMPTZ DEFAULT NOW(),
    fecha_cierre TIMESTAMPTZ,
    monto_inicial NUMERIC(10, 2) DEFAULT 0.00,
    estado TEXT DEFAULT 'ABIERTO', -- 'ABIERTO' | 'CERRADO'
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. TABLA: ventas
CREATE TABLE IF NOT EXISTS public.ventas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bodega_id TEXT NOT NULL,
    turno_caja_id BIGINT REFERENCES public.turnos_caja(id) ON DELETE SET NULL,
    cajero_id TEXT NOT NULL,
    cliente_id BIGINT REFERENCES public.clientes(id) ON DELETE SET NULL,
    nro_boleta TEXT NOT NULL,
    medio_pago TEXT NOT NULL DEFAULT 'EFECTIVO',
    total_venta NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. TABLA: ventas_detalle
CREATE TABLE IF NOT EXISTS public.ventas_detalle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id BIGINT REFERENCES public.ventas(id) ON DELETE CASCADE,
    producto_id BIGINT REFERENCES public.productos(id) ON DELETE SET NULL,
    cantidad NUMERIC(10, 2) NOT NULL DEFAULT 1,
    precio_unitario NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    subtotal NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- POLÍTICAS RLS (Row Level Security) - Permitir lectura y escritura con clave ANON
-- ==============================================================================
ALTER TABLE public.productos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.clientes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.turnos_caja ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ventas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ventas_detalle ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Permitir todo a anon en productos" ON public.productos FOR ALL TO anon USING (true) WITH CHECK (true);
CREATE POLICY "Permitir todo a anon en clientes" ON public.clientes FOR ALL TO anon USING (true) WITH CHECK (true);
CREATE POLICY "Permitir todo a anon en turnos_caja" ON public.turnos_caja FOR ALL TO anon USING (true) WITH CHECK (true);
CREATE POLICY "Permitir todo a anon en ventas" ON public.ventas FOR ALL TO anon USING (true) WITH CHECK (true);
CREATE POLICY "Permitir todo a anon en ventas_detalle" ON public.ventas_detalle FOR ALL TO anon USING (true) WITH CHECK (true);

